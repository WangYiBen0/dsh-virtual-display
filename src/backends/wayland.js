// Wayland backend: three tiers, cheapest first.
//
//   1. `mutter`  — headless Wayland compositor with a virtual monitor. This is
//      the only tier that works on a GPU-less host: mutter creates a surfaceless
//      renderer and never needs DRM.
//   2. `sway`    — headless sway with Xwayland. Preferable when a GPU exists,
//      because it gives DRI3 and real GL/Vulkan passthrough.
//   3. `xwayland`— fall back to a private X server. Not really Wayland, but it
//      keeps the platform usable when no compositor can start, and it still
//      never touches the user's session.
//
// `gamescope --backend headless` and `kwin_wayland --virtual` are deliberately
// NOT tried first: both were measured to be non-viable on GPU-less hosts
// (gamescope aborts in MouseCursor::getTexture after vkAllocateMemory fails,
// kwin cannot inherit capabilities in this sandbox). They remain as last-ditch
// attempts before the Xwayland fallback.

import { existsSync, readdirSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { spawn, run, sleep } from '../exec.js'
import { X11Backend } from './x11.js'

/**
 * Generation order. Earlier entries are cheaper and more reliable here.
 *
 * sway comes first because it is the only compositor in this list that both
 * works without a GPU *and* implements the screen-capture protocol grim needs.
 * mutter can start headless on a GPU-less host (surfaceless renderer) but it
 * only exposes GNOME's portal-based screenshot API, so grim against it fails
 * with "compositor doesn't support the screen capture protocol" — it is only
 * useful as a fallback for callers who supply their own capture path.
 */
const COMPOSITOR_ORDER = ['sway', 'mutter', 'gamescope', 'kwin_wayland']

export class WaylandBackend {
  name = 'wayland'

  async start(ctx, opts) {
    const attempts = []
    for (const kind of COMPOSITOR_ORDER) {
      const binary = opts.tools[kind]
      if (binary === undefined) continue
      if (kind === 'gamescope' && opts.allowGamescope === false) continue
      if (kind === 'kwin_wayland' && opts.allowKwin === false) continue
      try {
        return await this.launch(ctx, opts, { kind, binary })
      } catch (error) {
        attempts.push(`${kind}: ${firstLine(error?.message ?? String(error))}`)
      }
    }

    // No compositor worked. Fall back to a private X server and say so.
    const fallback = new X11Backend()
    const session = await fallback.start(ctx, opts)
    session.backend = 'wayland'
    session.mode = 'xwayland'
    session.waylandNote =
      'no private Wayland compositor could start on this host; used a private X server with XWayland semantics'
    session.compositorAttempts = attempts
    return session
  }

  /**
   * Write a minimal sway config.
   *
   * A headless sway with no `output` directive leaves the framebuffer fully
   * transparent, and grim then captures an all-zero PNG — which is
   * indistinguishable from a broken capture. A solid background makes "did the
   * compositor paint" observable.
   */
  writeSwayConfig(opts) {
    const path = join(opts.runtimeDir, 'sway.conf')
    const background = opts.swayBackground ?? '#163A6B'
    const lines = [
      '# generated by dsh-virtual-display; do not edit',
      `output * bg ${background} solid_color`,
      'default_border none',
      'default_floating_border none',
      'hide_edge_borders both',
      'xwayland enable',
      '',
    ]
    writeFileSync(path, lines.join('\n'))
    return path
  }

  /** Build the argv for each compositor's headless mode. */
  compositorArgv(compositor, opts, waylandDisplay) {
    const { kind, binary } = compositor
    const width = opts.width
    const height = opts.height

    if (kind === 'mutter') {
      // --headless works without a GPU: mutter logs "Created surfaceless
      // renderer without GPU". --virtual-monitor adds the output we render to.
      return [
        binary,
        '--wayland',
        '--headless',
        `--wayland-display=${waylandDisplay}`,
        '--virtual-monitor',
        `${width}x${height}`,
      ]
    }

    if (kind === 'sway') {
      // sway has no headless flag: the backend is selected by WLR_BACKENDS
      // (set in launch()), and it needs a config file to render a background —
      // an output-less sway produces a fully transparent screencopy result.
      return [binary, '-c', opts.swayConfig, '--unsupported-gpu']
    }

    if (kind === 'gamescope') {
      return [
        binary,
        '--backend',
        'headless',
        '--expose-wayland',
        '--xwayland-count',
        '1',
        '-W',
        String(width),
        '-H',
        String(height),
        '--',
        'sleep',
        'infinity',
      ]
    }

    return [
      binary,
      '--virtual',
      `--socket=${waylandDisplay}`,
      '--no-lockscreen',
      '--no-global-shortcuts',
    ]
  }

  async launch(ctx, opts, compositor) {
    const waylandDisplay = opts.waylandDisplay ?? `wayland-vd-${process.pid}`

    if (compositor.kind === 'sway' && opts.swayConfig === undefined) {
      opts.swayConfig = this.writeSwayConfig(opts)
    }
    const argv = this.compositorArgv(compositor, opts, waylandDisplay)

    // The compositor must not see the user's live session, or it would try to
    // nest inside it. The private runtime dir is what it publishes into.
    const env = { ...opts.env, XDG_RUNTIME_DIR: opts.runtimeDir }
    delete env.WAYLAND_DISPLAY
    delete env.DISPLAY

    // Re-point WAYLAND_DISPLAY at our own socket name, inside the private
    // runtime dir. Compositors differ here: mutter honours
    // `--wayland-display=`, while wlroots-based ones (sway) always call
    // wl_display_add_socket_auto and publish `wayland-1` regardless. The wait
    // loop below therefore adopts whatever socket actually appears rather than
    // insisting on the requested name.
    env.WAYLAND_DISPLAY = waylandDisplay

    if (compositor.kind === 'sway') {
      // sway picks its backend from the environment, not from argv. `headless`
      // is the only backend that works without DRM; without it sway exits with
      // "Failed to open any DRM device".
      env.WLR_BACKENDS = 'headless'
      env.WLR_LIBINPUT_NO_DEVICES = '1'
      env.WLR_RENDERER = opts.swayRenderer ?? 'pixman'
    }

    const handle = spawn(ctx, argv, {
      env,
      stdout: { maxBytes: 1 << 18 },
      stderr: { maxBytes: 1 << 18 },
      graceMs: 3000,
    })

    const deadline = Date.now() + (opts.compositorTimeoutMs ?? 10000)
    while (Date.now() < deadline) {
      // A compositor that exits has already failed; report its stderr rather
      // than waiting out the full timeout.
      const exited = await Promise.race([handle.done, sleep(200).then(() => undefined)])
      if (exited !== undefined) {
        const stderr = handle.collected?.stderr?.readFrom(0)?.text ?? ''
        throw new Error(
          `${compositor.kind} exited with code ${exited.exitCode}: ${stderr.trim().slice(0, 300)}`,
        )
      }
      const actual = findWaylandSocket(opts.runtimeDir)
      if (actual !== undefined) {
        // wlroots compositors put their control socket in the runtime dir too.
        // Publishing it in displayEnv means `swaymsg` works from any child
        // process without the caller having to hunt for the socket path.
        const swayIpc = findSwaySocket(opts.runtimeDir)
        const displayEnv = { WAYLAND_DISPLAY: actual, XDG_RUNTIME_DIR: opts.runtimeDir }
        if (swayIpc !== undefined) displayEnv.SWAYSOCK = swayIpc
        return {
          backend: 'wayland',
          mode: compositor.kind,
          waylandDisplay: actual,
          displayEnv,
          sockets: [`${opts.runtimeDir}/${actual}`],
          handle,
          runtimeDir: opts.runtimeDir,
          width: opts.width,
          height: opts.height,
          startedAt: Date.now(),
        }
      }
    }

    try {
      handle.terminate()
    } catch {
      // Already gone.
    }
    throw new Error(`${compositor.kind} did not publish ${waylandDisplay} within the timeout`)
  }

  async capture(ctx, session, opts) {
    if (session.mode === 'xwayland' || session.mode === undefined) {
      return new X11Backend().capture(ctx, session, opts)
    }

    const grim = opts.tools.grim
    if (grim === undefined) {
      throw new Error(
        `cannot capture a nested Wayland session (${session.mode}): grim is not available on this host`,
      )
    }

    const result = await run(ctx, [grim, opts.destPath], {
      env: { ...opts.env, ...session.displayEnv },
      maxBytes: 1 << 20,
      signal: opts.signal,
    })
    if (result.exitCode !== 0) {
      throw new Error(`wayland capture failed (exit ${result.exitCode}): ${result.stderr.trim()}`)
    }
    return opts.destPath
  }

  async listWindows(ctx, session, opts) {
    if (session.mode === 'xwayland' || session.mode === undefined) {
      return new X11Backend().listWindows(ctx, session, opts)
    }
    // Wayland has no portable window-enumeration protocol. sway exposes one via
    // its IPC socket; mutter exposes nothing without a private D-Bus interface.
    if (session.mode === 'sway' && opts.tools.swaymsg !== undefined) {
      const result = await run(ctx, [opts.tools.swaymsg, '-t', 'get_tree', '-r'], {
        env: { ...opts.env, ...session.displayEnv },
        maxBytes: 1 << 20,
      })
      if (result.exitCode === 0) {
        try {
          return flattenSwayTree(JSON.parse(result.stdout))
        } catch {
          return []
        }
      }
    }
    return []
  }

  async settle(ctx, session, opts) {
    await sleep(opts.settleMs ?? 1500, opts.signal)
    return session
  }

  async stop(ctx, session) {
    try {
      session.handle.terminate()
      await session.handle.waitForExit()
    } catch {
      // Already gone.
    }
  }
}

/** Flatten sway's nested container tree into { id, title } windows. */
function flattenSwayTree(node, out = []) {
  if (node === null || typeof node !== 'object') return out
  const title =
    node.name ?? node.app_id ?? node.window_properties?.title ?? node.shell ?? ''
  if (node.pid !== undefined || node.app_id !== undefined || node.window_properties !== undefined) {
    out.push({ id: String(node.id ?? ''), title: String(title) })
  }
  for (const child of node.nodes ?? []) flattenSwayTree(child, out)
  for (const child of node.floating_nodes ?? []) flattenSwayTree(child, out)
  return out
}

function firstLine(text) {
  return String(text).split('\n')[0].slice(0, 160)
}

/**
 * Find the Wayland socket this session just published.
 *
 * The runtime dir is per-session and private, so any `wayland-*` entry in it
 * belongs to the compositor we started — no need to guess the exact name. The
 * `-lock` sidecars and `*.sock` IPC files are skipped.
 */
/** Find sway's IPC socket, if this compositor publishes one. */
function findSwaySocket(runtimeDir) {
  let entries
  try {
    entries = readdirSync(runtimeDir)
  } catch {
    return undefined
  }
  for (const entry of entries) {
    if (!entry.startsWith('sway-ipc.')) continue
    if (!entry.endsWith('.sock')) continue
    return join(runtimeDir, entry)
  }
  return undefined
}

function findWaylandSocket(runtimeDir) {
  let entries
  try {
    entries = readdirSync(runtimeDir)
  } catch {
    return undefined
  }
  for (const entry of entries) {
    if (!entry.startsWith('wayland-')) continue
    if (entry.endsWith('.lock')) continue
    if (!existsSync(join(runtimeDir, entry))) continue
    return entry
  }
  return undefined
}
